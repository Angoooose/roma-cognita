/**
 * The people layer: DPRR and Wikidata, from the cache that dprr.ts and wikidata.ts
 * fetched, normalised into build/people/ (PEOPLE.md §4).
 *
 *   npm run people -w pipeline
 *
 * What normalising means here:
 *
 * - **Years become astronomical.** DPRR writes 63 BCE as −63 and has no year zero;
 *   we write it as −62. `dprrYear` is the only place that conversion happens.
 * - **DPRR's era is used only where it is unambiguous.** 507 people have an era
 *   ending in 0, a year that does not exist in DPRR's numbering, and several hundred
 *   more end on a positive year that is sometimes CE and sometimes a lost minus sign.
 *   A person's `active` span therefore comes from their dated posts, statuses and
 *   life events, and falls back to the era only when both ends are BCE.
 * - **Relationships become one edge per pair.** DPRR stores most twice (Cicero *son
 *   of* Helvia, Helvia *mother of* Cicero), one side often "Autogenerated by
 *   add_inverse". Each pair is matched through DPRR's inverse table, which is keyed
 *   by the relationship and the sex of the other person, and merged.
 * - **Corrections to DPRR are applied and reported** (corrections.ts).
 *
 * The output is CC BY-NC 4.0, like DPRR, and is never copied into data/ (PEOPLE.md §2).
 */
