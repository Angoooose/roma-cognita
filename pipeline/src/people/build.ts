// --- reading DPRR's values ----------------------------------------------------------

/**
 * A DPRR year as an astronomical one: −63 (63 BCE) → −62, 14 (14 CE) → 14. DPRR's
 * numbering has no zero, so a zero is an error in the data, and so is anything that
 * is not a whole number.
 */
export function dprrYear(value: string): Year {
  const n = Number(value)
  if (!Number.isInteger(n) || n === 0) throw new Error(`not a DPRR year: "${value}"`)
  return n < 0 ? n + 1 : n
}

/** The id at the end of a DPRR entity URI: `…/entity/Person/2072` → 2072. */
export function entityId(uri: string): number {
  const n = Number(uri.slice(uri.lastIndexOf('/') + 1))
  if (!Number.isInteger(n)) throw new Error(`no numeric id in ${uri}`)
  return n
}

const personId = (uri: string): PersonId => `dprr:${entityId(uri)}`
const flag = (v: string | undefined) => v === 'true'
const asserted = (value: string, uncertain: string | undefined): AssertedYear => ({
  year: dprrYear(value),
  uncertain: flag(uncertain),
})

// --- names --------------------------------------------------------------------------

/** "M. Tullius Cicero": praenomen, nomen, cognomen. DPRR writes an unknown praenomen as "-.". */
export function displayName(p: {
  praenomen?: string
  nomen?: string
  cognomen?: string
}): string {
  const praenomen = p.praenomen && p.praenomen !== '-.' ? p.praenomen : undefined
  return [praenomen, p.nomen, p.cognomen]
    .filter(Boolean)
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim()
}

/**
 * DPRR's label without its code or RE number: "TULL2072 M. Tullius (29) M. f. M. n.
 * Cor. Cicero" → "M. Tullius M. f. M. n. Cor. Cicero". An RE number appearing later,
 * in an alternative name after "=", is kept: it belongs to that name.
 */
export function fullName(label: string, code: string, re: string | undefined): string {
  let s = label.startsWith(code) ? label.slice(code.length) : label
  if (re) s = s.replace(` (${re})`, '')
  return s.replace(/\s+/g, ' ').trim()
}

// --- corrections --------------------------------------------------------------------

export interface CorrectionReport {
  applied: Correction[]
  stale: { correction: Correction; found: string | undefined }[]
}

/** Applies each correction whose expected value is still there, in place. */
export function applyCorrections(
  tables: Pick<Record<Table, Row[]>, 'posts' | 'statuses'>,
  corrections: Correction[],
): CorrectionReport {
  const report: CorrectionReport = { applied: [], stale: [] }
  const idField = { posts: 'post', statuses: 'assertion' } as const
  for (const e of corrections) {
    const row = tables[e.table].find((r) => entityId(r[idField[e.table]]!) === e.id)
    if (!row || row[e.field] !== e.expect) {
      report.stale.push({ correction: e, found: row?.[e.field] })
      continue
    }
    row[e.field] = e.value
    report.applied.push(e)
  }
  return report
}

// --- relationships ------------------------------------------------------------------

export interface RelationshipAssertion {
  id: number
  person: PersonId
  related: PersonId
  type: number
  uncertain: boolean
  source: number
  extra?: string
  citations: string[]
  notes: string[]
}

export interface CollapseReport {
  /** Assertions whose mirror was found and merged into one edge. */
  merged: number
  /** Assertions repeating an edge already made, folded into it. */
  duplicates: number
  /** Assertions with no mirror: kept as an edge of their own. */
  unmatched: number
  /** Types with no inverse for the other person's sex. */
  noInverse: Set<string>
}

/**
 * Merges each assertion with its mirror (`b` *inverse* of `a`) into one edge. The
 * edge takes the direction DPRR's editors wrote, not the one its script generated;
 * between two written ones, the lower assertion id.
 */
export function collapseRelationships(
  assertions: RelationshipAssertion[],
  sexOf: (p: PersonId) => 'male' | 'female' | undefined,
  inverseOf: (type: number, sex: 'male' | 'female') => number | undefined,
): { edges: RelationshipRecord[]; report: CollapseReport } {
  const report: CollapseReport = {
    merged: 0,
    duplicates: 0,
    unmatched: 0,
    noInverse: new Set(),
  }
  const key = (a: PersonId, b: PersonId, t: number) => `${a}|${b}|${t}`
  const open = new Map<string, RelationshipAssertion[]>()
  for (const a of [...assertions].sort((x, y) => x.id - y.id)) {
    const k = key(a.person, a.related, a.type)
    open.set(k, [...(open.get(k) ?? []), a])
  }
  const inverse = (a: RelationshipAssertion) => {
    const sex = sexOf(a.related)
    const inv = sex ? inverseOf(a.type, sex) : undefined
    if (inv === undefined) report.noInverse.add(`${a.type}/${sex ?? '?'}`)
    return inv ?? null
  }
  const take = (k: string) => {
    const list = open.get(k)
    const first = list?.shift()
    if (list && !list.length) open.delete(k)
    return first
  }

  const edges: RelationshipRecord[] = []
  // Edges by either direction, so a repeated assertion can find the edge it repeats.
  const made = new Map<string, RelationshipRecord>()
  for (const a of [...assertions].sort((x, y) => x.id - y.id)) {
    const k = key(a.person, a.related, a.type)
    if (!open.get(k)?.includes(a)) continue // already merged as someone's mirror
    take(k)
    const inv = inverse(a)
    const mirror = inv === null ? undefined : take(key(a.related, a.person, inv))
    const pair = mirror ? [a, mirror] : [a]
    // DPRR sometimes states the same relationship twice, singly or as a second pair.
    const repeated = made.get(k)
    if (repeated) {
      report.duplicates += pair.length
      repeated.uncertain ||= pair.some((x) => x.uncertain)
      repeated.sources = [...new Set([...repeated.sources, ...pair.map((x) => x.source)])]
      repeated.citations = [
        ...new Set([...repeated.citations, ...pair.flatMap((x) => x.citations)]),
      ]
      repeated.assertions.push(...pair.map((x) => x.id))
      continue
    }
    if (mirror) report.merged += 2
    else report.unmatched++
    const primary = pair.find((x) => x.extra !== AUTOGENERATED) ?? pair[0]
    const notes = pair.flatMap((x) => [
      ...(x.extra && x.extra !== AUTOGENERATED ? [x.extra] : []),
      ...x.notes,
    ])
    edges.push({
      a: primary.person,
      b: primary.related,
      type: primary.type,
      inverse: primary === a ? inv : a.type,
      uncertain: pair.some((x) => x.uncertain),
      sources: [...new Set(pair.map((x) => x.source))],
      citations: [...new Set(pair.flatMap((x) => x.citations))],
      notes: [...new Set(notes)],
      assertions: pair.map((x) => x.id),
    })
    const edge = edges[edges.length - 1]
    made.set(key(edge.a, edge.b, edge.type), edge)
    if (edge.inverse !== null) made.set(key(edge.b, edge.a, edge.inverse), edge)
  }
  return { edges, report }
}

// --- active span --------------------------------------------------------------------

/**
 * The years a person is attested: the span of their dated assertions, or DPRR's era
 * where both its ends are BCE (a positive end is sometimes CE and sometimes a lost
 * sign; a zero end is not a year at all).
 */
export function activeSpan(
  years: Year[],
  era: { from: string; to: string },
): PersonRecord['active'] {
  if (years.length) {
    return { from: Math.min(...years), to: Math.max(...years), basis: 'assertions' }
  }
  const from = Number(era.from)
  const to = Number(era.to)
  if (Number.isInteger(from) && Number.isInteger(to) && from < 0 && to < 0 && from <= to) {
    return { from: dprrYear(era.from), to: dprrYear(era.to), basis: 'era' }
  }
  return undefined
}

// --- build --------------------------------------------------------------------------

function main() {
  const t0 = Date.now()
  const { manifest: dprrManifest, tables } = readDprr()
  let wikidata: Map<number, WikidataPerson> | null = null
  try {
    wikidata = readWikidata()
  } catch (err) {
    console.warn(`  no Wikidata cache, so no English names: ${(err as Error).message}`)
  }

  const corrections = applyCorrections(tables, CORRECTIONS)

  // Authorities.
  const offices = tables.offices.map((o) => ({
    id: entityId(o.office!),
    name: o.name!,
    ...(o.abbreviation ? { abbreviation: o.abbreviation } : {}),
    ...(o.parent ? { parent: entityId(o.parent) } : {}),
  }))
  const roles = classifyOffices(offices)
  const authorities: Authorities = {
    offices: offices.map((o) => ({ ...o, role: roles.get(o.id)! })),
    provinces: tables.provinces.map((p) => ({
      id: entityId(p.province!),
      // One of DPRR's provinces has neither a name nor a description.
      name: p.name ?? p.description ?? `province ${entityId(p.province!)}`,
      ...(p.description ? { description: p.description } : {}),
      ...(p.parent ? { parent: entityId(p.parent) } : {}),
    })),
    relationships: tables.relationshipTypes.map((r) => ({
      id: entityId(r.relationship!),
      name: r.name!,
      ...(r.order ? { order: Number(r.order) } : {}),
    })),
    statuses: tables.statusTypes.map((s) => ({
      id: entityId(s.status!),
      name: s.name!,
      ...(s.abbreviation ? { abbreviation: s.abbreviation } : {}),
    })),
    sources: tables.sources.map((s) => ({
      id: entityId(s.source!),
      name: s.name!,
      ...(s.abbreviation ? { abbreviation: s.abbreviation } : {}),
      ...(s.biblio && s.biblio !== 'NA' ? { biblio: s.biblio } : {}),
    })),
  }

  // Ancient citations, by the assertion they support.
  const citationsFor = new Map<string, string[]>()
  const cite = (uri: string, text: string | undefined) => {
    if (!text?.trim()) return
    citationsFor.set(uri, [...(citationsFor.get(uri) ?? []), text.trim()])
  }
  for (const r of tables.primaryReferences) cite(r.assertion!, r.citation)
  const relNotes = new Map<string, string[]>()
  for (const r of tables.relationshipReferences) {
    cite(r.assertion!, r.citation)
    if (r.note?.trim())
      relNotes.set(r.assertion!, [...(relNotes.get(r.assertion!) ?? []), r.note.trim()])
  }

  // Posts, and the provinces they name.
  const provincesOf = new Map<string, PostRecord['provinces']>()
  for (const r of tables.postProvinces) {
    const list = provincesOf.get(r.post!) ?? []
    list.push({ id: entityId(r.province!), uncertain: flag(r.uncertain) })
    provincesOf.set(r.post!, list)
  }
  const posts: PostRecord[] = tables.posts.map((r) => ({
    id: entityId(r.post!),
    person: personId(r.person!),
    office: entityId(r.office!),
    from: asserted(r.start!, r.startU),
    to: asserted(r.end!, r.endU),
    uncertain: flag(r.uncertain),
    provinces: provincesOf.get(r.post!) ?? [],
    ...(r.provinceOriginal ? { provinceText: r.provinceOriginal } : {}),
    source: entityId(r.source!),
    ...(r.original ? { original: r.original } : {}),
    citations: citationsFor.get(r.post!) ?? [],
  }))

  const statuses: StatusRecord[] = tables.statuses.map((r) => ({
    id: entityId(r.assertion!),
    person: personId(r.person!),
    status: entityId(r.status!),
    ...(r.start ? { from: asserted(r.start, r.startU) } : {}),
    ...(r.end ? { to: asserted(r.end, r.endU) } : {}),
    uncertain: flag(r.uncertain),
    source: entityId(r.source!),
    ...(r.original ? { original: r.original } : {}),
    citations: citationsFor.get(r.assertion!) ?? [],
  }))

  const BOUND = { S: 'on', B: 'before', A: 'after' } as const
  const lifeEvents: LifeEventRecord[] = tables.lifeDates.map((r) => ({
    id: entityId(r.info!),
    person: personId(r.person!),
    type: r.type!,
    year: dprrYear(r.value!),
    bound: BOUND[(r.interval ?? 'S') as keyof typeof BOUND] ?? 'on',
    uncertain: flag(r.uncertain),
    ...(r.source ? { source: entityId(r.source) } : {}),
    ...(r.note ? { note: r.note } : {}),
  }))

  // People.
  const yearsOf = new Map<PersonId, Year[]>()
  const addYears = (p: PersonId, ...ys: (Year | undefined)[]) => {
    const list = yearsOf.get(p) ?? []
    for (const y of ys) if (y !== undefined) list.push(y)
    yearsOf.set(p, list)
  }
  for (const p of posts) addYears(p.person, p.from.year, p.to.year)
  for (const s of statuses) addYears(s.person, s.from?.year, s.to?.year)
  for (const e of lifeEvents) addYears(e.person, e.year)

  let eraUnreadable = 0
  const persons: PersonRecord[] = tables.persons.map((r) => {
    const id = personId(r.person!)
    const dprrId = entityId(r.person!)
    const active = activeSpan(yearsOf.get(id) ?? [], { from: r.eraFrom!, to: r.eraTo! })
    if (!active) eraUnreadable++
    const uncertainNames = (
      [
        ['praenomen', r.praenomenU],
        ['nomen', r.nomenU],
        ['cognomen', r.cognomenU],
        ['filiation', r.filiationU],
        ['otherNames', r.otherNamesU],
      ] as const
    )
      .filter(([, u]) => flag(u))
      .map(([n]) => n)
    const wd = wikidata?.get(dprrId)
    return {
      id,
      name: displayName(r),
      full: fullName(r.label!, r.code!, r.re),
      re: r.re ?? '',
      sex: r.sex === 'Female' ? 'female' : 'male',
      names: {
        ...(r.praenomen && r.praenomen !== '-.' ? { praenomen: r.praenomen } : {}),
        ...(r.altPraenomen ? { altPraenomen: r.altPraenomen } : {}),
        nomen: r.nomen!,
        ...(r.cognomen ? { cognomen: r.cognomen } : {}),
        ...(r.otherNames ? { otherNames: r.otherNames } : {}),
        ...(r.filiation?.trim() ? { filiation: r.filiation.trim() } : {}),
      },
      ...(uncertainNames.length ? { uncertainNames } : {}),
      ...(flag(r.patrician) ? { patrician: { uncertain: flag(r.patricianU) } } : {}),
      ...(flag(r.nobilis) ? { nobilis: true as const } : {}),
      ...(flag(r.novus) ? { novus: true as const } : {}),
      ...(r.origin ? { origin: r.origin } : {}),
      ...(r.highestOffice ? { highestOffice: r.highestOffice } : {}),
      ...(active ? { active } : {}),
      ...(wd
        ? {
            en: {
              wikidata: wd.qid,
              ...(wd.label ? { label: wd.label } : {}),
              ...(wd.description ? { description: wd.description } : {}),
              aliases: wd.aliases,
              ...(wd.image ? { image: wd.image } : {}),
            },
          }
        : {}),
      dprr: {
        id: dprrId,
        code: r.code!,
        page: r.page ?? `https://romanrepublic.ac.uk/person/${dprrId}`,
      },
    }
  })
  const byId = new Map(persons.map((p) => [p.id, p]))

  // Relationships.
  const inverses = new Map<string, number>()
  for (const r of tables.relationshipInverses) {
    inverses.set(
      `${entityId(r.relationship!)}|${r.sex!.toLowerCase()}`,
      entityId(r.inverse!),
    )
  }
  const typeByName = new Map(authorities.relationships.map((r) => [r.name, r.id]))
  const inverseCorrections: string[] = []
  for (const e of INVERSE_CORRECTIONS) {
    const type = typeByName.get(e.type)
    const inverse = typeByName.get(e.inverse)
    if (type === undefined || inverse === undefined) {
      inverseCorrections.push(
        `OUT-OF-DATE INVERSE CORRECTION ${e.type} / ${e.sex}: DPRR has no relationship named "${type === undefined ? e.type : e.inverse}"`,
      )
      continue
    }
    const k = `${type}|${e.sex}`
    const had = inverses.get(k)
    if ((e.kind === 'add') !== (had === undefined)) {
      inverseCorrections.push(
        `OUT-OF-DATE INVERSE CORRECTION ${e.type} / ${e.sex} (${e.kind}): DPRR's table ${had === undefined ? 'has no row' : 'now has a row'}`,
      )
      continue
    }
    inverses.set(k, inverse)
    if (e.kind === 'fix')
      inverseCorrections.push(
        `OVERRODE inverse of "${e.type}" for a ${e.sex}: → "${e.inverse}"`,
      )
  }
  const supplied = INVERSE_CORRECTIONS.filter((e) => e.kind === 'add').length
  const { edges: relationships, report: collapse } = collapseRelationships(
    tables.relationships.map((r) => ({
      id: entityId(r.assertion!),
      person: personId(r.person!),
      related: personId(r.related!),
      type: entityId(r.relationship!),
      uncertain: flag(r.uncertain),
      source: entityId(r.source!),
      ...(r.extra ? { extra: r.extra } : {}),
      citations: citationsFor.get(r.assertion!) ?? [],
      notes: relNotes.get(r.assertion!) ?? [],
    })),
    (p) => byId.get(p)?.sex,
    (type, sex) => inverses.get(`${type}|${sex}`),
  )

  // A pair each said to be the other's father (or son, or uncle) is a contradiction in
  // DPRR. Both edges are kept, and reported, rather than one silently chosen.
  const contradictions: string[] = []
  const edgeKey = new Set(relationships.map((r) => `${r.a}|${r.b}|${r.type}`))
  for (const r of relationships) {
    if (r.inverse === r.type || r.a > r.b) continue
    if (edgeKey.has(`${r.b}|${r.a}|${r.type}`)) {
      const type = authorities.relationships.find((t) => t.id === r.type)!.name
      contradictions.push(
        `${byId.get(r.a)!.name} (${r.a}) and ${byId.get(r.b)!.name} (${r.b}) are each "${type}" the other`,
      )
    }
  }

  // Every reference must land.
  const problems: string[] = []
  const officeIds = new Set(offices.map((o) => o.id))
  const provinceIds = new Set(authorities.provinces.map((p) => p.id))
  const sourceIds = new Set(authorities.sources.map((s) => s.id))
  for (const p of posts) {
    if (!byId.has(p.person)) problems.push(`post ${p.id}: no person ${p.person}`)
    if (!officeIds.has(p.office)) problems.push(`post ${p.id}: no office ${p.office}`)
    if (!sourceIds.has(p.source)) problems.push(`post ${p.id}: no source ${p.source}`)
    for (const pr of p.provinces)
      if (!provinceIds.has(pr.id)) problems.push(`post ${p.id}: no province ${pr.id}`)
    if (p.to.year < p.from.year) problems.push(`post ${p.id}: ends before it starts`)
  }
  for (const r of relationships) {
    for (const p of [r.a, r.b])
      if (!byId.has(p)) problems.push(`relationship ${r.assertions}: no person ${p}`)
  }
  for (const s of statuses)
    if (!byId.has(s.person)) problems.push(`status ${s.id}: no person ${s.person}`)
  for (const e of lifeEvents)
    if (!byId.has(e.person)) problems.push(`life event ${e.id}: no person ${e.person}`)
  if (problems.length) {
    throw new Error(
      `DPRR references that do not resolve:\n  ${problems.slice(0, 30).join('\n  ')}`,
    )
  }

  const search: SearchEntry[] = persons.map((p) => {
    const label = p.en?.label && p.en.label !== p.name ? p.en.label : undefined
    const terms = [
      ...new Set([
        p.full,
        ...(p.en?.aliases ?? []),
        ...(p.names.otherNames ? [p.names.otherNames] : []),
      ]),
    ]
    return {
      id: p.id,
      name: p.name,
      ...(label ? { label } : {}),
      terms: terms.filter((t) => t !== p.name && t !== label),
      re: p.re,
      ...(p.highestOffice ? { highestOffice: p.highestOffice } : {}),
      ...(p.active ? { active: [p.active.from, p.active.to] as [Year, Year] } : {}),
    }
  })

  // Write.
  rmSync(OUT, { recursive: true, force: true })
  mkdirSync(OUT, { recursive: true })
  // Governors: DPRR's posts joined to our polities through data/dprr-provinces.yaml.
  const table = readDprrProvinces(DATA_DIR)
  const dataset = loadDataset()
  const provinceNames = new Map(authorities.provinces.map((p) => [p.id, p.name]))
  const { records: governorships, report: joined } = table
    ? joinGovernors(
        posts,
        (id) => provinceNames.get(id),
        (office) => roles.get(office),
        table,
        new Set(dataset.polities.map((p) => p.id)),
        new Set(provinceNames.values()),
      )
    : { records: [], report: null }
  if (joined && (joined.unknownNames.length || joined.unknownPolities.length)) {
    throw new Error(
      `data/dprr-provinces.yaml: ${[
        ...joined.unknownNames.map((n) => `no DPRR province named "${n}"`),
        ...joined.unknownPolities.map((p) => `no polity "${p}"`),
      ].join('; ')}`,
    )
  }
  // The years each polity was a province on our map, to find the ones with nobody attested.
  const provinceYears = new Map<string, Set<Year>>()
  if (table) {
    const joinedPolities = new Set(table.flatMap((t) => t.polities.map((p) => p.polity)))
    for (const c of dataset.claims) {
      if (c.relation !== 'province' || !joinedPolities.has(c.polity)) continue
      const years = provinceYears.get(c.polity) ?? new Set<Year>()
      for (let y = c.from.year; y <= c.to.year; y++) years.add(y)
      provinceYears.set(c.polity, years)
    }
  }
  const unattested = unattestedYears(provinceYears, governorships)

  const files = {
    persons,
    posts,
    relationships,
    statuses,
    lifeEvents,
    authorities,
    search,
    governorships: {
      polities: table
        ? [...new Set(table.flatMap((t) => t.polities.map((p) => p.polity)))].sort()
        : [],
      records: governorships,
    } satisfies Governorships,
  }
  for (const [name, data] of Object.entries(files)) {
    writeFileSync(join(OUT, `${name}.json`), JSON.stringify(data))
  }
  const manifest: PeopleManifest = {
    built: new Date().toISOString(),
    dprr: { endpoint: dprrManifest.endpoint, fetched: dprrManifest.fetched },
    ...(wikidata ? { wikidata: { fetched: wikidataFetched() } } : {}),
    licence: 'CC BY-NC 4.0',
    counts: Object.fromEntries(
      Object.entries(files)
        .filter(([, d]) => Array.isArray(d))
        .map(([n, d]) => [n, (d as unknown[]).length]),
    ),
  }
  writeFileSync(join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n')
  writeFileSync(join(OUT, 'LICENSE'), LICENSE)

  // Report: what the build could not confirm, and what it overrode (DESIGN §1.6).
  const byRole = new Map<OfficeRole, number>()
  for (const r of roles.values()) byRole.set(r, (byRole.get(r) ?? 0) + 1)
  const usedOffices = new Set(posts.map((p) => p.office))
  const unclassified = authorities.offices.filter(
    (o) => o.role === 'other' && usedOffices.has(o.id),
  )
  const withProvince = posts.filter((p) => p.provinces.length).length
  const n = (x: number) => x.toLocaleString('en')
  console.log(
    `people: ${n(persons.length)} persons, ${n(posts.length)} posts (${n(withProvince)} with a province), ${n(relationships.length)} relationships, ${n(statuses.length)} statuses, ${n(lifeEvents.length)} life events`,
  )
  console.log(
    `  relationships: ${n(tables.relationships.length)} assertions → ${n(relationships.length)} edges (${n(collapse.merged)} merged in pairs, ${n(collapse.duplicates)} repeats folded in, ${n(collapse.unmatched)} with no mirror)`,
  )
  for (const c of contradictions) console.log(`  CONTRADICTION in DPRR: ${c}`)
  console.log(
    `  inverse table: ${supplied} rows supplied where DPRR has none (corrections.ts)`,
  )
  for (const line of inverseCorrections) console.log(`  ${line}`)
  if (collapse.noInverse.size) {
    const name = new Map(authorities.relationships.map((r) => [r.id, r.name]))
    const missing = [...collapse.noInverse].map((k) => {
      const [t, sex] = k.split('/')
      return `"${name.get(Number(t))}" for a ${sex}`
    })
    console.log(`  NO INVERSE, so not merged: ${missing.join(', ')}`)
  }
  console.log(`  offices: ${[...byRole].map(([r, c]) => `${c} ${r}`).join(', ')}`)
  if (unclassified.length)
    console.log(`  UNCLASSIFIED offices: ${unclassified.map((o) => o.name).join('; ')}`)
  console.log(
    `  active span: ${n(persons.filter((p) => p.active?.basis === 'assertions').length)} from assertions, ${n(persons.filter((p) => p.active?.basis === 'era').length)} from DPRR's era, ${n(eraUnreadable)} undated`,
  )
  console.log(
    `  English names: ${wikidata ? `${n(persons.filter((p) => p.en).length)} of ${n(persons.length)} from Wikidata` : 'none (no Wikidata cache)'}`,
  )
  if (!table) {
    console.log('  governors: none (no data/dprr-provinces.yaml yet)')
  } else {
    const polities = new Set(governorships.map((g) => g.polity))
    console.log(
      `  governors: ${n(governorships.filter((g) => g.role === 'command').length)} commands and ${n(governorships.filter((g) => g.role === 'staff').length)} staff years across ${polities.size} polities`,
    )
    if (joined!.unlisted.size) {
      console.log(
        `  NOT IN dprr-provinces.yaml: ${[...joined!.unlisted].map(([name, c]) => `${name} (${c} posts)`).join(', ')}`,
      )
    }
    for (const [polity, years] of unattested) {
      console.log(`  NO GOVERNOR ATTESTED in ${polity}: ${spans(years)}`)
    }
  }
  for (const e of corrections.applied)
    console.log(
      `  OVERRODE ${e.table} ${e.id} ${e.field} ${e.expect} → ${e.value}: ${e.why}`,
    )
  for (const { correction: e, found } of corrections.stale) {
    console.log(
      `  OUT-OF-DATE CORRECTION ${e.table} ${e.id} ${e.field}: expected ${e.expect}, found ${found ?? 'no such row'} (${e.why})`,
    )
  }
  console.log(`wrote ${OUT} in ${((Date.now() - t0) / 1000).toFixed(1)} s`)
}

/** −66, −65, −64, −60 → "67–65 BCE, 61 BCE". */
function spans(years: Year[]): string {
  const out: string[] = []
  for (let i = 0; i < years.length;) {
    let j = i
    while (j + 1 < years.length && years[j + 1] === years[j] + 1) j++
    out.push(i === j ? formatYear(years[i]) : `${1 - years[i]}–${formatYear(years[j])}`)
    i = j + 1
  }
  return out.join(', ')
}

/** When the Wikidata cache was fetched, for the manifest. */
function wikidataFetched(): string {
  const path = join(ROOT_DIR, '.cache/sources/dprr/wikidata.json')
  return existsSync(path)
    ? (JSON.parse(readFileSync(path, 'utf8')) as { fetched: string }).fetched
    : ''
}

